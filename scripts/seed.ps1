function Post($table, $body) {
    $json  = $body | ConvertTo-Json -Depth 10 -Compress
    $bytes = [System.Text.Encoding]::UTF8.GetBytes($json)
    $r = Invoke-RestMethod -Uri "$SUPA_URL/$table" -Method Post -Headers $HEADERS -Body $bytes
    return $r
}
function PostMin($table, $body) {
    $json  = $body | ConvertTo-Json -Depth 10 -Compress
    $bytes = [System.Text.Encoding]::UTF8.GetBytes($json)
    Invoke-RestMethod -Uri "$SUPA_URL/$table" -Method Post -Headers $H_MIN -Body $bytes | Out-Null
}
function NewUid { [System.Guid]::NewGuid().ToString() }

function SeedFragment($storyId, $fragId, $layer, $rarity, $label, $text, $time, $weather, $date, $atm, $scenes) {
    Write-Host "  frag: $label" -ForegroundColor Cyan
    PostMin "story_fragments" @{
        id = $fragId; story_id = $storyId
        layer = $layer; rarity = $rarity
        fragment_label = $label; fragment_text = $text
        time_condition = $time; weather_condition = $weather; date_condition = $date
        motif_tags = @(); is_user_submitted = $false
    }

    $atmRows = $atm | ForEach-Object { @{ id = (NewUid); story_fragment_id = $fragId; atmosphere_text = $_ } }
    PostMin "fragment_atmosphere" $atmRows

    foreach ($sc in $scenes) {
        $scRow = @{
            id = (NewUid); story_fragment_id = $fragId
            layer_index = $sc.idx; atmosphere_text = $sc.text
            is_skippable = $sc.skip
            ending_high = $sc.endH; ending_low = $sc.endL
        }
        $inserted = Post "fragment_scenes" $scRow
        $sceneId = $inserted.id
        Write-Host "    layer $($sc.idx) → scene $sceneId" -ForegroundColor DarkGray

        $optRows = $sc.opts | ForEach-Object {
            @{ id = (NewUid); scene_id = $sceneId; text = $_.text; signal_delta = $_.delta; result_text = $_.result }
        }
        PostMin "scene_options" $optRows
    }
}

